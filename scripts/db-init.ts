/**
 * Idempotent database bootstrap. Safe to run repeatedly: it only creates
 * things that do not exist yet, so existing data (todos, users, business, ...)
 * is never touched and no duplicate columns/constraints are created.
 *
 * Uses the shared pg pool from src/lib/db.ts — no second connection pool.
 *
 * Run with:  npm run db:init
 */
import pool from "../src/lib/db.ts";
import { ensureIdSequences } from "../src/lib/idSequences.ts";

async function main(): Promise<void> {
  // gen_random_uuid() needs pgcrypto (already enabled on Neon; no-op here).
  await pool.query(`CREATE EXTENSION IF NOT EXISTS "pgcrypto";`);

  // Business table (UUID PK generated by PostgreSQL).
  await pool.query(`
    CREATE TABLE IF NOT EXISTS business (
      id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      business_name VARCHAR(255) NOT NULL,
      email         VARCHAR(255) UNIQUE NOT NULL,
      created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
    );
  `);

  // Legacy local installs may still have a business_name column on users;
  // make it nullable so inserts that no longer set it keep working.
  await pool.query(`
    DO $$
    BEGIN
      IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'users' AND column_name = 'business_name'
      ) THEN
        ALTER TABLE users ALTER COLUMN business_name DROP NOT NULL;
      END IF;
    END $$;
  `);

  // users.business_id column (no-op if it already exists, e.g. on Neon).
  await pool.query(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS business_id UUID;
  `);

  // users.business_id FK -> business.id (skip if it already exists).
  await pool.query(`
    DO $$
    BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'users_business_id_fkey'
      ) THEN
        ALTER TABLE users
          ADD CONSTRAINT users_business_id_fkey
          FOREIGN KEY (business_id) REFERENCES business(id) ON DELETE CASCADE;
      END IF;
    END $$;
  `);

  // Clinic locations (multi-branch clinics per business).
  await pool.query(`
    CREATE TABLE IF NOT EXISTS clinic_locations (
      id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      business_id   UUID NOT NULL REFERENCES business(id) ON DELETE CASCADE,
      clinic_name   VARCHAR(255) NOT NULL,
      city          VARCHAR(100) NOT NULL,
      clinic_code   VARCHAR(50)  NOT NULL,
      contact_phone VARCHAR(30)  NOT NULL,
      full_address  TEXT         NOT NULL,
      working_days  VARCHAR(255) NOT NULL,
      opening_time  TIME         NOT NULL,
      closing_time  TIME         NOT NULL,
      status        VARCHAR(30)  NOT NULL DEFAULT 'active',
      google_maps_url TEXT,
      latitude      DECIMAL(10, 7),
      longitude     DECIMAL(10, 7),
      created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
      updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
      UNIQUE (business_id, clinic_code)
    );
  `);

  // Doctor profile (one per business) for the "Manage Doctor Profile" form.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS doctor_profiles (
      id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      business_id    UUID NOT NULL UNIQUE REFERENCES business(id) ON DELETE CASCADE,
      photo_url      TEXT,
      full_name      VARCHAR(255) NOT NULL,
      professional_title VARCHAR(255),
      specialty      VARCHAR(255),
      experience     VARCHAR(100),
      qualifications TEXT,
      additional_qualifications TEXT,
      short_bio      TEXT,
      full_bio       TEXT,
      professional_interests TEXT,
      areas_of_expertise TEXT,
      phone          VARCHAR(30),
      email           VARCHAR(255),
      languages       VARCHAR(255),
      clinic_id      UUID REFERENCES clinic(id) ON DELETE SET NULL,
      created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
      updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
    );
  `);

  // Patients (per business). patient_id is human-readable (PT-YYYYMMDD-XXXX),
  // unique within the business. No image/photo column by design.
  // age is app-level REQUIRED (validation layer); the column stays nullable so
  // legacy rows keep loading. New installs get it from day one.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS patient (
      id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      business_id    UUID NOT NULL REFERENCES business(id) ON DELETE CASCADE,
      patient_id     VARCHAR(50)  NOT NULL,
      full_name      VARCHAR(255) NOT NULL,
      gender         VARCHAR(30),
      date_of_birth  DATE,
      age            INTEGER,
      marital_status VARCHAR(50),
      phone          VARCHAR(50),
      alternate_phone VARCHAR(50),
      email          VARCHAR(255),
      full_address   TEXT,
      city           VARCHAR(100),
      emergency_contact_name VARCHAR(255),
      emergency_contact_relationship VARCHAR(100),
      emergency_contact_phone VARCHAR(50),
      allergies      TEXT,
      medical_conditions TEXT,
      current_medications TEXT,
      previous_surgeries TEXT,
      family_medical_history TEXT,
      medical_notes  TEXT,
      status         VARCHAR(30)  NOT NULL DEFAULT 'active',
      created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
      updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
      UNIQUE (business_id, patient_id)
    );
  `);
  await pool.query(
    "CREATE INDEX IF NOT EXISTS patient_business_idx ON patient (business_id, created_at DESC)"
  );

  // Appointments (per business). References the EXISTING patient,
  // doctor_profiles and clinic tables — no duplicate entity tables. Names
  // are never stored here; they are resolved through JOINs.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS appointment (
      id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      business_id     UUID NOT NULL REFERENCES business(id) ON DELETE CASCADE,
      appointment_id  VARCHAR(50) NOT NULL,
      patient_id      UUID NOT NULL REFERENCES patient(id) ON DELETE CASCADE,
      doctor_id       UUID NOT NULL REFERENCES doctor_profiles(id) ON DELETE CASCADE,
      clinic_id       UUID NOT NULL REFERENCES clinic(id) ON DELETE CASCADE,
      appointment_date DATE NOT NULL,
      appointment_time TIME NOT NULL,
      appointment_type VARCHAR(50) NOT NULL,
      reason          TEXT,
      notes           TEXT,
      status          VARCHAR(30) NOT NULL DEFAULT 'scheduled',
      created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (business_id, appointment_id)
    );
  `);
  await pool.query(
    "CREATE INDEX IF NOT EXISTS appointment_business_idx ON appointment (business_id, appointment_date DESC)"
  );
  await pool.query(
    "CREATE INDEX IF NOT EXISTS appointment_slot_idx ON appointment (business_id, doctor_id, clinic_id, appointment_date, appointment_time)"
  );

  // Two COMPLETELY INDEPENDENT sequences for the human-readable IDs:
  //   patient_id_sequence      START 1    -> PT-YYYYMMDD-0001, 0002, ...
  //   appointment_id_sequence  START 5001 -> APT-YYYYMMDD-5001, 5002, ...
  // Idempotent + forward-only: creates them if missing and fast-forwards
  // past any ID that already exists for today, so new records can never
  // duplicate an existing ID. Existing records are never modified.
  const seqClient = await pool.connect();
  try {
    await seqClient.query("BEGIN");
    await ensureIdSequences(seqClient);
    await seqClient.query("COMMIT");
  } catch (err) {
    await seqClient.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    seqClient.release();
  }

  console.log("Database bootstrap complete: business/users/clinic_locations/doctor_profiles/patient/appointment schema is ready.");
}

main()
  .then(() => pool.end())
  .then(() => process.exit(0))
  .catch((err: unknown) => {
    console.error("Database bootstrap failed:", err);
    process.exitCode = 1;
    return pool.end();
  });
